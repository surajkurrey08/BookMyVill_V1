#!/usr/bin/env node
// Writes docs/api/gateway-routes.md from shared/serviceCatalog.js.
//   node scripts/generate-gateway-docs.js
const fs = require('fs');
const path = require('path');
const { SERVICES, SPECIAL_ROUTES, publicPaths } = require('../shared/serviceCatalog');

const rows = Object.entries(SERVICES).map(([name, def]) => `| ${name} | ${def.port} | ${def.app ? `independent${def.database ? ` (own DB \`${def.database.key}_*\`)` : ''}` : 'legacy-shared'} | ${def.purpose} | ${publicPaths(def).map(p => `\`${p}\``).join(', ')} |`);
const specials = SPECIAL_ROUTES.map(rule => `\`${rule.method} ${rule.path.source.replace(/\\\//g, '/')}\` → ${rule.service}`).join('; ');

const doc = `# API Gateway routes

Generated by \`backend/scripts/generate-gateway-docs.js\` from \`backend/shared/serviceCatalog.js\`. All clients call the gateway (\`https://api.bookmyvilla.online\`, locally \`http://localhost:2001\`); services are never called directly, and \`/internal/*\` paths are never routed by the gateway.

| Service | Internal port | Type | Responsibility | Public paths |
|---|---|---|---|---|
${rows.join('\n')}

Special rules (checked before prefixes): ${specials}.

Every legacy path keeps working unchanged. \`/api/v1/<domain>\` aliases are the stable versioned entry points for new clients.

Gateway endpoints: \`GET /health\` (gateway process), \`GET /ready\` and \`GET /api/health\` (critical services ready — used by the deploy check), \`GET /metrics\`.
`;
const out = path.join(__dirname, '..', '..', 'docs', 'api', 'gateway-routes.md');
fs.writeFileSync(out, doc);
console.log(`Wrote ${out}`);
